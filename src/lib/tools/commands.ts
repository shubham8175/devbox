export const TOTAL_COMMANDS = COMMAND_SECTIONS.reduce((n, s) => n + s.entries.length, 0);

export const MAX_QUERY_LENGTH = 200;

export interface CommandHit {
  entry: CommandEntry;
  score: number;
}

export interface SectionResult {
  section: CommandSection;
  hits: CommandHit[];
}

/** The OS an entry is limited to, inherited from its section when not set. */
export function platformOf(entry: CommandEntry, section: CommandSection): CommandPlatform | undefined {
  return entry.platform ?? section.platform;
}

function scoreTerm(term: string, entry: CommandEntry, section: CommandSection): number {
  const cmd = entry.cmd.toLowerCase();
  if (cmd === term) return 10;
  if (cmd.startsWith(term)) return 8;
  if (cmd.split(/[\s|&;=/]+/).some((w) => w.replace(/^-+/, "").startsWith(term))) return 6;
  if (cmd.includes(term)) return 5;
  if (entry.keywords?.some((k) => k.toLowerCase().includes(term))) return 4;
  if (entry.description.toLowerCase().includes(term)) return 3;
  if (section.title.toLowerCase().includes(term)) return 2;
  if (platformOf(entry, section)?.toLowerCase().includes(term)) return 2;
  if (section.keywords?.some((k) => k.toLowerCase().includes(term))) return 1;
  return 0;
}

/**
 * Filter sections by stack or section id, then by query. Every query term must
 * match somewhere (command, keywords, description, section title or section
 * keywords). With a query, hits are ranked within a section and sections are
 * ranked by their best hit; without one, the curated order is kept.
 */
export function searchCommands(query: string, filter: { stack?: CommandStack | null; sectionId?: string | null } = {}): SectionResult[] {
  const terms = query.slice(0, MAX_QUERY_LENGTH).trim().toLowerCase().split(/\s+/).filter(Boolean);
  const results: Array<SectionResult & { best: number; order: number }> = [];
  COMMAND_SECTIONS.forEach((section, order) => {
    if (filter.stack && section.stack !== filter.stack) return;
    if (filter.sectionId && section.id !== filter.sectionId) return;
    const hits: CommandHit[] = [];
    for (const entry of section.entries) {
      let score = 0;
      let matched = true;
      for (const term of terms) {
        const s = scoreTerm(term, entry, section);
        if (!s) {
          matched = false;
          break;
        }
        score += s;
      }
      if (matched) hits.push({ entry, score });
    }
    if (!hits.length) return;
    if (terms.length) hits.sort((a, b) => b.score - a.score);
    results.push({ section, hits, best: hits[0].score, order });
  });
  if (terms.length) results.sort((a, b) => b.best - a.best || a.order - b.order);
  return results.map(({ section, hits }) => ({ section, hits }));
}

/** Split a command into literal text and <placeholder> parts for rendering. */
export function splitPlaceholders(cmd: string): Array<{ text: string; placeholder: boolean }> {
  // split() with a capturing group puts the captured placeholders at odd indices.
  return cmd
    .split(PLACEHOLDER_RE)
    .map((text, i) => ({ text, placeholder: i % 2 === 1 }))
    .filter((part) => part.text.length > 0);
}
