/**
 * Command cheatsheet: a static, curated list of terminal commands grouped by
 * tool or stack, each with a one-line explanation. Search is local and
 * synchronous; nothing is fetched or executed.
 */

export type CommandStack = "Git & GitHub" | "Shell & OS" | "JavaScript" | "Frameworks" | "Python" | "More languages" | "Mobile" | "Infra & Data" | "Troubleshooting";

export type CommandPlatform = "macOS" | "Linux" | "Windows";

export interface CommandEntry {
  cmd: string;
  description: string;
  /** Destroys work or data, or kills processes. Shown with a warning badge. */
  danger?: boolean;
  /** Only works on this OS. Omitted when the command is cross-platform or Unix-wide. */
  platform?: CommandPlatform;
  /** Extra search terms that appear in neither the command nor the description. */
  keywords?: string[];
}

export interface CommandSection {
  id: string;
  title: string;
  stack: CommandStack;
  /** Search terms that apply to every command in the section. */
  keywords?: string[];
  /** Applies to every entry that does not set its own. */
  platform?: CommandPlatform;
  entries: CommandEntry[];
}

